/*
事务操作

方式一：关闭自动提交，手动控制事务

1. 查看/设置事务提交方式
SELECT @@autocommit;
SET @@autocommit = 0;

2. 提交事务
COMMIT;

3. 回滚事务
ROLLBACK;

方式二：显式开启事务

1. 开启事务（以下两种语句任选其一）
START TRANSACTION;
-- 或
BEGIN;

2. 提交事务
COMMIT;

3. 回滚事务
ROLLBACK;

实际开发中如何决定提交或回滚：
1. 通常由 Go、Java 等后端语言编写 if 判断和错误处理。
2. 后端程序检查 SQL 是否报错，以及业务条件是否满足（如余额是否充足）。
   全部成功则提交事务；中途报错或业务条件不满足则回滚事务，并停止后续操作。
3. MySQL 负责执行 SQL，以及程序发出的 COMMIT 或 ROLLBACK 指令。

注意：
    SQL 没报错不代表业务成功，例如 UPDATE 影响 0 行可能表示账户不存在或余额不足。
    某条 SQL 报错也不一定会自动回滚整个事务，程序仍需处理回滚。
    MySQL 的存储过程也支持 IF 和异常处理，但常见业务逻辑通常写在后端程序中。
*/
